import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
import fs from 'node:fs';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.SITE_URL || 'http://127.0.0.1:3001';
const browser = await chromium.launch();
try {
 const page = await browser.newPage({ viewport: { width:1440,height:1000 } });
 page.setDefaultTimeout(20000); const errors=[];page.on('pageerror',e=>errors.push(e.message));
 fs.mkdirSync('.next/buyer-review',{recursive:true});
 await page.goto(base+'/export-from-india',{waitUntil:'networkidle'});
 assert.deepEqual(await page.locator('.buyer-panel[id] h3').allTextContents(),['India','UK','USA','Europe','UAE']);
 const schemas=await page.locator('script[type="application/ld+json"]').allTextContents();
 assert.deepEqual(schemas.map(JSON.parse).find(s=>s['@type']==='Organization').areaServed.map(s=>s.name),['India','United Kingdom','United States','Europe','United Arab Emirates']);
 await page.getByRole('button',{name:'Discuss supply to UAE',exact:false}).click();
 const form=page.locator('.enquiry-dialog');assert.equal(await form.locator('[name=country]').inputValue(),'UAE');
 assert.deepEqual(await form.locator('[name=country] option:not([value=""])').allTextContents(),['India','UK','USA','Europe','UAE','Any other']);
 await page.keyboard.press('Escape');
 await page.goto(base+'/contact',{waitUntil:'networkidle'});
 await page.locator('.contact-atlas').getByRole('button',{name:'Click here for directions'}).click();
 assert.equal(await page.locator('.atlas-satellite-layer').count(),0);
 await page.waitForFunction(()=>document.querySelector('.contact-atlas').dataset.mapPhase==='map');
 const directions=page.locator('.atlas-actions a');assert.equal(await directions.isVisible(),true);assert.match(await directions.getAttribute('href'),/google.com\/maps\/dir/);
 await page.locator('.atlas-map-loading').waitFor({state:'hidden',timeout:25000});
 await page.locator('.contact-atlas').screenshot({path:'.next/buyer-review/contact-map-transition.png'});
 console.log('PASS: five shipping markets, structured coverage, prefilled destination selector and original globe-to-map directions flow.');
 await page.goto(base+'/products',{waitUntil:'networkidle'});
 const construction=page.locator('.range-row-compact').filter({hasText:'Construction Admixtures'});
 await construction.hover();assert.equal(await construction.getAttribute('data-open'),'true');
 await page.mouse.move(1,1);assert.equal(await construction.getAttribute('data-open'),'false');
 const photoSources=await page.locator('.range-photo img').evaluateAll(nodes=>nodes.map(n=>n.getAttribute('src')));
 assert.ok(photoSources.every(src=>src.includes('photos')||decodeURIComponent(src).includes('/photos/')));
 await construction.hover();await construction.screenshot({path:'.next/buyer-review/construction-hover.png'});
 await page.goto(base+'/',{waitUntil:'networkidle'});
 await page.waitForFunction(()=>document.querySelector('.trade-journey-v2')?.dataset.scrollEnd);
 const movePhase=async time=>{await page.evaluate(time=>{const el=document.querySelector('.trade-journey-v2');scrollTo(0,Number(el.dataset.scrollStart)+(Number(el.dataset.scrollEnd)-Number(el.dataset.scrollStart))*time/40)},time);await page.waitForFunction(time=>Math.abs(Number(document.querySelector('.trade-journey-v2').dataset.phase)-time)<.12,time);};
 await movePhase(1.5);
 const gaps=await page.locator('.motion-stat').evaluateAll(rows=>rows.slice(1).map((row,i)=>row.getBoundingClientRect().top-rows[i].getBoundingClientRect().bottom));assert.ok(gaps.every(gap=>gap>=0&&gap<=42));
 await page.screenshot({path:'.next/buyer-review/stat-spacing.png'});
 await movePhase(8.5);await page.waitForTimeout(1500);await page.screenshot({path:'.next/buyer-review/branded-container-stack.png'});
 await page.goto(base+'/about',{waitUntil:'networkidle'});await page.waitForFunction(()=>document.querySelector('logistics-about')?.dataset.brandStyle==='unbranded');
 assert.deepEqual(errors,[]);
 console.log('PASS: construction hover, refreshed catalog photos, tighter statistics spacing, baked side branding and unbranded door containers and no runtime errors.');
} finally {await browser.close();}
